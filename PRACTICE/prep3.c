#include <stdio.h>

int main()
 {
    int a = 15;
    int b = 25;

    printf("Given values: a = %d, b = %d\n\n", a, b);

    printf("a > b: %d (False)\n", a > b);

    printf("a < b: %d (True)\n", a < b);

    printf("a >= b: %d (False)\n", a >= b);

    printf("a <= b: %d (True)\n", a <= b);

    printf("a == b: %d (False)\n", a == b);

    printf("a != b: %d (True)\n", a != b);

    return 0;
}
